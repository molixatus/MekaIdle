'use strict';
// Database access. Uses PostgreSQL when DATABASE_URL is set (Railway), otherwise a local SQLite
// file, so the game runs locally with nothing to install. Queries use `?` placeholders in both.
//
// All work happens inside tx(): one transaction at a time, in the order requested. Each API
// request is one transaction, so a player's state can't be changed by two requests at once and
// a failed request leaves nothing half-saved.
//
// Keeping data safe through patches:
// - The schema is changed only by the numbered steps in MIGRATIONS. Each runs once, in order, and
//   is recorded in schema_migrations. Steps only ever add (tables, columns, indexes); never drop
//   or rewrite data here. To change the schema, append a new step; never edit an old one.
// - Player saves are JSON upgraded in code by migrate() in lib/game.js. Before a save is upgraded
//   to a new version, the untouched original is copied to save_backups (see backupSave()).
// - On first start with an empty PostgreSQL database, any existing SQLite database (for example
//   on an old Railway volume) is copied in, so switching to Postgres keeps everyone's progress.
const fs = require('node:fs');
const path = require('node:path');

const TABLES = ['players', 'sessions', 'friends', 'guilds', 'guild_chat', 'trades', 'parties', 'party_members', 'save_backups'];

// Schema steps. `pg` tells a step which dialect it's writing for.
const MIGRATIONS = [
  { v: 1, name: 'base tables', sql: pg => {
    const id = pg ? 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'INTEGER PRIMARY KEY';
    const big = pg ? 'BIGINT' : 'INTEGER';
    return [
      `CREATE TABLE IF NOT EXISTS players (
        id ${id}, name TEXT NOT NULL, name_key TEXT NOT NULL UNIQUE, pass TEXT NOT NULL,
        mech TEXT NOT NULL, colour TEXT NOT NULL, state TEXT NOT NULL,
        guild_id ${big}, guild_joined ${big}, total_level INTEGER NOT NULL DEFAULT 6, power INTEGER NOT NULL DEFAULT 0,
        created ${big} NOT NULL, last_seen ${big} NOT NULL)`,
      `CREATE TABLE IF NOT EXISTS sessions (token TEXT PRIMARY KEY, player_id ${big} NOT NULL, expires ${big} NOT NULL)`,
      `CREATE TABLE IF NOT EXISTS friends (a ${big} NOT NULL, b ${big} NOT NULL, status TEXT NOT NULL, created ${big} NOT NULL, PRIMARY KEY (a, b))`,
      `CREATE TABLE IF NOT EXISTS guilds (id ${id}, name TEXT NOT NULL, name_key TEXT NOT NULL UNIQUE, tag TEXT NOT NULL UNIQUE,
        leader_id ${big} NOT NULL, created ${big} NOT NULL)`,
      `CREATE TABLE IF NOT EXISTS guild_chat (id ${id}, guild_id ${big} NOT NULL, player_id ${big} NOT NULL,
        name TEXT NOT NULL, text TEXT NOT NULL, at ${big} NOT NULL)`,
      `CREATE TABLE IF NOT EXISTS trades (id ${id}, from_id ${big} NOT NULL, to_id ${big} NOT NULL,
        give TEXT NOT NULL, want TEXT NOT NULL, status TEXT NOT NULL, created ${big} NOT NULL, updated ${big} NOT NULL)`,
      `CREATE TABLE IF NOT EXISTS parties (id ${id}, leader_id ${big} NOT NULL, raid TEXT NOT NULL, created ${big} NOT NULL)`,
      `CREATE TABLE IF NOT EXISTS party_members (party_id ${big} NOT NULL, player_id ${big} NOT NULL UNIQUE, joined ${big} NOT NULL)`,
      'CREATE INDEX IF NOT EXISTS guild_chat_guild ON guild_chat (guild_id, id)',
      'CREATE INDEX IF NOT EXISTS trades_to ON trades (to_id, status)',
      'CREATE INDEX IF NOT EXISTS trades_from ON trades (from_id, status)',
      'CREATE INDEX IF NOT EXISTS players_guild ON players (guild_id)',
    ];
  } },
  { v: 2, name: 'columns added after launch', columns: [
    ['parties', 'session', 'TEXT'],
    ['players', 'combat_level', 'INTEGER NOT NULL DEFAULT 4'],
    ['players', 'activity', 'TEXT'],
    ['players', 'guild_rank', 'TEXT'],
    ['parties', 'diff', "TEXT NOT NULL DEFAULT 'normal'"],
    ['parties', 'visibility', "TEXT NOT NULL DEFAULT 'friends'"],
  ] },
  { v: 3, name: 'save backups', sql: pg => [
    `CREATE TABLE IF NOT EXISTS save_backups (id ${pg ? 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'INTEGER PRIMARY KEY'},
      player_id ${pg ? 'BIGINT' : 'INTEGER'} NOT NULL, version INTEGER NOT NULL, reason TEXT NOT NULL, state TEXT NOT NULL, at ${pg ? 'BIGINT' : 'INTEGER'} NOT NULL)`,
    'CREATE INDEX IF NOT EXISTS save_backups_player ON save_backups (player_id, id)',
  ] },
];
const BACKUPS_KEPT = 5;

// Runs fn(...) one at a time, in call order.
function serial() {
  let chain = Promise.resolve();
  return fn => {
    const run = chain.then(fn);
    chain = run.catch(() => {});
    return run;
  };
}

// Applies any schema steps not yet recorded. `addColumn` knows each dialect's way of adding a
// column only if it's missing.
async function migrateSchema(db, pg, addColumn) {
  await db.run(`CREATE TABLE IF NOT EXISTS schema_migrations (version INTEGER PRIMARY KEY, name TEXT NOT NULL, applied ${pg ? 'BIGINT' : 'INTEGER'} NOT NULL)`);
  const done = new Set((await db.all('SELECT version FROM schema_migrations')).map(r => r.version));
  for (const m of MIGRATIONS) {
    if (done.has(m.v)) continue;
    for (const sql of m.sql ? m.sql(pg) : []) await db.run(sql);
    for (const [table, col, type] of m.columns || []) await addColumn(table, col, type);
    await db.run('INSERT INTO schema_migrations (version, name, applied) VALUES (?, ?, ?)', m.v, m.name, Date.now());
    console.log(`Database: applied schema step ${m.v} (${m.name}).`);
  }
  await db.run('DROP TABLE IF EXISTS raid_runs');
}

// Keeps a copy of a save exactly as it was, and trims each player's backups to the newest few.
async function backupSave(db, playerId, version, reason, stateJson) {
  await db.run('INSERT INTO save_backups (player_id, version, reason, state, at) VALUES (?, ?, ?, ?, ?)', playerId, version, reason, stateJson, Date.now());
  const old = await db.all('SELECT id FROM save_backups WHERE player_id = ? ORDER BY id DESC LIMIT 1000 OFFSET ?', playerId, BACKUPS_KEPT);
  for (const r of old) await db.run('DELETE FROM save_backups WHERE id = ?', r.id);
}

async function openPostgres(url, dir) {
  const { Pool, types } = require('pg');
  // BIGINT (timestamps, ids, counts) and NUMERIC (sums) come back as numbers, not strings.
  types.setTypeParser(20, v => Number(v));
  types.setTypeParser(1700, v => Number(v));
  const ssl = /sslmode=(require|verify)/.test(url) || process.env.PGSSLMODE === 'require' ? { rejectUnauthorized: false } : undefined;
  const pool = new Pool({ connectionString: url, ssl, max: 1, idleTimeoutMillis: 60000, connectionTimeoutMillis: 15000 });
  pool.on('error', e => console.error('Postgres connection error (it will reconnect):', e.message));
  let client = null;
  const toPg = sql => { let n = 0; return sql.replace(/\?/g, () => `$${++n}`); };
  const query = async (sql, params) => {
    if (!client) throw new Error('Database used outside a transaction.');
    return client.query(toPg(sql), params);
  };
  const queue = serial();
  const db = {
    kind: 'postgres',
    get: async (sql, ...p) => (await query(sql, p)).rows[0],
    all: async (sql, ...p) => (await query(sql, p)).rows,
    run: async (sql, ...p) => ({ changes: (await query(sql, p)).rowCount }),
    insert: async (sql, ...p) => (await query(`${sql} RETURNING id`, p)).rows[0].id,
    backupSave: (...a) => backupSave(db, ...a),
    tx: fn => queue(async () => {
      const c = await pool.connect();
      client = c;
      let broken = false;
      try {
        await c.query('BEGIN');
        const r = await fn();
        await c.query('COMMIT');
        return r;
      } catch (e) {
        try { await c.query('ROLLBACK'); } catch (e2) { broken = true; }
        throw e;
      } finally {
        client = null;
        c.release(broken);
      }
    }),
    close: () => pool.end(),
  };
  await db.tx(async () => {
    await migrateSchema(db, true, (t, col, type) => db.run(`ALTER TABLE ${t} ADD COLUMN IF NOT EXISTS ${col} ${type}`));
    await importSqlite(db, dir);
  });
  return db;
}

// Copies an existing SQLite database into a PostgreSQL one that has no players yet.
async function importSqlite(db, dir) {
  const file = dir && path.join(dir, 'mekaidle.db');
  if (!file || !fs.existsSync(file)) return;
  if ((await db.get('SELECT COUNT(*) AS n FROM players')).n > 0) return;
  const { DatabaseSync } = require('node:sqlite');
  const lite = new DatabaseSync(file, { readOnly: true });
  const has = t => !!lite.prepare("SELECT name FROM sqlite_master WHERE type = 'table' AND name = ?").get(t);
  let copied = 0;
  for (const table of TABLES) {
    if (!has(table)) continue;
    const cols = (await db.all('SELECT column_name FROM information_schema.columns WHERE table_name = ?', table)).map(r => r.column_name);
    for (const row of lite.prepare(`SELECT * FROM ${table}`).all()) {
      const keys = Object.keys(row).filter(k => cols.includes(k));
      await db.run(`INSERT INTO ${table} (${keys.join(', ')}) VALUES (${keys.map(() => '?').join(', ')})`, ...keys.map(k => row[k]));
      if (table === 'players') copied++;
    }
    // New rows must get ids after the copied ones.
    if (cols.includes('id')) await db.run(`SELECT setval(pg_get_serial_sequence('${table}', 'id'), GREATEST((SELECT COALESCE(MAX(id), 0) FROM ${table}), 1))`);
  }
  lite.close();
  console.log(`Database: imported ${copied} pilots from ${file} into PostgreSQL.`);
}

async function openSqlite(dir) {
  const { DatabaseSync } = require('node:sqlite');
  fs.mkdirSync(dir, { recursive: true });
  const file = path.join(dir, 'mekaidle.db');
  const sqlite = new DatabaseSync(file);
  sqlite.exec('PRAGMA journal_mode = WAL');
  const stmts = new Map();
  const prep = sql => {
    if (!stmts.has(sql)) stmts.set(sql, sqlite.prepare(sql));
    return stmts.get(sql);
  };
  const queue = serial();
  const db = {
    kind: 'sqlite',
    file,
    get: async (sql, ...p) => prep(sql).get(...p),
    all: async (sql, ...p) => prep(sql).all(...p),
    run: async (sql, ...p) => ({ changes: Number(prep(sql).run(...p).changes) }),
    insert: async (sql, ...p) => Number(prep(sql).run(...p).lastInsertRowid),
    backupSave: (...a) => backupSave(db, ...a),
    tx: fn => queue(async () => {
      sqlite.exec('BEGIN IMMEDIATE');
      try {
        const r = await fn();
        sqlite.exec('COMMIT');
        return r;
      } catch (e) {
        sqlite.exec('ROLLBACK');
        throw e;
      }
    }),
    close: async () => sqlite.close(),
  };
  await db.tx(() => migrateSchema(db, false, async (t, col, type) => {
    const cols = (await db.all(`PRAGMA table_info(${t})`)).map(r => r.name);
    if (!cols.includes(col)) await db.run(`ALTER TABLE ${t} ADD COLUMN ${col} ${type}`);
  }));
  return db;
}

async function open({ url, dir }) {
  return url ? openPostgres(url, dir) : openSqlite(dir);
}

module.exports = { open };
